pairs = [("온도", 1.39), ("OP값", 13.75), ("CP값", 0.01)]
# 이 세 숫자는 밑에서 할 걸 숫자 열 셋의 '흔들림'을 잰 값입니다.
# 여기서 손으로 적어두고, 밑에서 같은 방법으로 다시 재서 맞춰 봅니다.

print("4) 흔들림 큰 순:", sorted(pairs, key=lambda t: -t[1]))  # t는("이름",값) 한 쌍
# 이 줄을 왼쪽부터 읽으면(한 줄에 세가지가 겹쳐 있어서 끊어 읽어야 함)
# sorted(pairs, ...) pairs를 줄 세운 새 목록을 만든다(원본pairs는 그대로)
# key=lambda t:-t[1] t[1]을 기준으로 줄 세우는데, -를 붙여서 큰 값이 앞으로 오게 한다.
# lambda t: ... 는 이름 없는 한줄 함수. "t를 받으면 -t[1]을 돌려줘"라는 뜻
# t는 ("온도",1.39) 같은 한 쌍이 들어오고, t[1]은 1.39를 뜻함


print("5) 삼항 연산자:", "넓다" if max(temps) - min(temps) > 10 else "좁다")
# 삼항연산자 = if문을 한 줄로 쓴것. A if 조건 else B = 조건이 참이면 A, 거짓이면 B

print(
    " 6)슬라이싱: temps[:3] =",
    temps[:3],
    "temps[-3:] =",
    temps[-3:],
    "temps[::-1][:3] =",
    temps[::-1][:3],
)
# tempp[:3] = 처음 3개, temps[-3:] = 마지막 3개, temps[::-1][:3] = 뒤집어서 처음 3개

kinds = {}  # 딕셔너리로 개수 세기
for row in rows:
    kinds[row[1]] = kinds.get(row[1], 0) + 1  # .get(키,0) = 없으면 0으로 시작

print(
    " 7) 딕셔너리로 세기:",
    kinds,
    "set 으로 종류만",
    sorted(set(row[5] for row in rows)),
)


