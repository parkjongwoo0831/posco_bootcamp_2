with open(LOT, encoding="utf-8-sig") as f:
    r = csv.reader(f)
    header = next(r)  # 첫줄은 열이름이어서 꺼냄
    rows = list(r)  # 나머지가 데이터

temps = [float(row[2]) for row in rows]  # 3번째 칸(온도)을 숫자로 바꿔 모음
print("2) 리스트 컴프리헨션:", temps[:5], "...총", len(temps), "개")

